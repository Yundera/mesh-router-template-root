#!/bin/bash
# ensure-maison-stack.sh - Deploy Maison behind its AppShield gate.
#
# Maison (github.com/Yundera/Maison) is the dashboard that replaces CasaOS: the same
# app grid and the same CasaOS App Store format, in a single Go binary driving the
# Docker socket. It has no file manager, no database, and no authentication of any
# kind — the gate in front of it is the only way in.
#
# Deployed to ${DATA_ROOT}/AppData/maison. The name carries no leading dot, so
# Maison's own managed-app scan (it skips any name containing a dot) picks the stack
# up and the dashboard tiles itself. That is deliberate: it is not hidden.
#
# SECURITY: the compose file never publishes Maison's port — the AppShield gate in
# the same stack is the only route in. Do not "temporarily" add a ports: mapping.
#
# ORDERING: must run AFTER ensure-auth-stack.sh. The gate needs auth-registrar / dex
# (auth stack) reachable by name on `pcs`, which it joins as external like every
# stack.
#
# Ported from Yundera/template-root; its CasaDash rebrand/legacy-path handling is
# omitted because this template never shipped `casadash`.
set -euo pipefail

# shellcheck disable=SC1091
source "$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)/library/common.sh"

MAISON_DIR="${DATA_ROOT:-/DATA}/AppData/maison"

# The maison container talks to the Docker socket as a non-root user, so it needs
# the socket's group. Resolve it from the host rather than assuming the usual 999.
if [ ! -S /var/run/docker.sock ]; then
    log_error "/var/run/docker.sock not found; cannot determine DOCKER_GID"
    exit 1
fi
DOCKER_GID="$(stat -c '%g' /var/run/docker.sock)"

# Maison stamps container timezones from TZ. The mesh .env does not carry it.
if [ -f /etc/timezone ]; then
    TZ="$(cat /etc/timezone 2>/dev/null || echo UTC)"
elif [ -L /etc/localtime ]; then
    TZ="$(readlink /etc/localtime | sed 's|.*/zoneinfo/||')"
else
    TZ="UTC"
fi

# --- .env.app: what every app Maison installs receives -----------------------
# The deployment's statement of the world it places apps into: the network they
# join, the domain and public IP their Caddy routes are templated with, the identity
# they seed an admin account from. Maison forwards each key into every app's own
# .env, on install and again on every start — so a box that changes domain or IP
# carries its apps with it instead of stranding them.
#
# It goes in the stack's own directory, which is also Maison's state directory
# (STATE_DIR is left unset, defaulting to DATA_ROOT/AppData/maison). Written BEFORE
# deploy-stack.sh, so a first-ever install finds it already there and never falls
# back to Maison's built-in default — that default is a standalone local install
# (APP_NET=mesh, no domain), and no such network exists here, so every app would
# fail to start.
mkdir -p "$MAISON_DIR"

env_get() { get_env_value "$1"; }

# Temp file + move: Maison reads .env.app from another container, at any moment, to
# start an app — it must never observe a half-written one.
APPENV_TMP="$(mktemp "$MAISON_DIR/.env.app.XXXXXX")"
cat > "$APPENV_TMP" <<EOF
# Generated by ensure-maison-stack.sh from the mesh .env.
# DO NOT EDIT — rewritten on every self-check. Change $ENV_FILE instead.
#
# The variables Maison forwards into every app it manages; see Maison's docs/app-env.md.
APP_NET=pcs
APP_DOMAIN=$(env_get DOMAIN)
domain=$(env_get DOMAIN)
APP_PUBLIC_IP=$(env_get PUBLIC_IP)
APP_PUBLIC_IP_DASH=$(env_get PUBLIC_IP_DASH)
APP_PUBLIC_IPV4=$(env_get PUBLIC_IPV4)
APP_PUBLIC_IPV4_DASH=$(env_get PUBLIC_IPV4_DASH)
APP_PUBLIC_IPV6=$(env_get PUBLIC_IPV6)
APP_PUBLIC_IPV6_DASH=$(env_get PUBLIC_IPV6_DASH)
APP_IP_ZONE=$(env_get IP_ZONE)
APP_EMAIL=$(env_get EMAIL)
APP_DEFAULT_PASSWORD=$(env_get DEFAULT_PWD)
DefaultUserName=admin
DefaultPassword=$(env_get DEFAULT_PWD)
EOF

# Carries DEFAULT_PWD, exactly as the mesh .env does. Maison runs as root and is
# the only reader.
chmod 600 "$APPENV_TMP"
mv -f "$APPENV_TMP" "$MAISON_DIR/.env.app"
echo "Wrote $MAISON_DIR/.env.app"

DEPLOY_RC=0
"$SCRIPTS_DIR/tools/deploy-stack.sh" maison "$MAISON_DIR" \
    "DOCKER_GID=$DOCKER_GID" \
    "TZ=$TZ" || DEPLOY_RC=$?

# --- settings Maison holds on the deployment's behalf ------------------------
# Through the `maison` CLI inside the container, never by editing Maison's state
# files: Maison holds them in memory and is their only writer (Maison's
# docs/config.md). A managed setting is read-only in the dashboard and shows its
# owner; this block re-asserts it on every self-check, and releases it when the
# feature is off here, which hands it back to the user.
#
# An image older than the CLI cannot take any of this. It still reads SMTP_*,
# FEEDBACK_* and APPSTORE_URL from the compose environment, which is why the
# compose keeps passing them: skip, and let that path carry the box.
if ! docker exec maison-app maison help >/dev/null 2>&1; then
    log_warn "maison-app predates the maison CLI; mail, feedback and the store stay on the env path"
    exit "$DEPLOY_RC"
fi

# Shown to the user as "Managed by <owner>". A deployment layered on this template
# names itself here (template-root sets Yundera).
OWNER="$(env_get MAISON_SETTINGS_OWNER)"
OWNER="${OWNER:-mesh}"
maison_cli() { docker exec -i maison-app maison "$@" >/dev/null; }
CLI_FAILED=0
# JSON is built by hand (no jq on the host); refuse a value that would break it.
json_safe() { case "$1" in *'"'* | *'\'*) return 1 ;; esac; }

# Mail: this stack's own relay, the `smtp` service. SMTP_TO only diverts the
# recipient; empty means Maison mails the box's owner (APP_EMAIL).
SMTP_TO_VAL="$(env_get SMTP_TO)"
if json_safe "$SMTP_TO_VAL"; then
    printf '{"host":"smtp","port":587,"security":"none","from":"","to":"%s"}' "$SMTP_TO_VAL" \
        | maison_cli settings set smtp --owner "$OWNER" || CLI_FAILED=1
else
    log_error "SMTP_TO contains a quote or backslash; mail setting not updated"
    CLI_FAILED=1
fi

# Routing: every app on the box's domain, nip.io and sslip.io — what store listings
# that ship their own caddy labels already have, stated for listings that ship
# `routes` and no labels — plus the mesh-router-nameserver's names when the .env has
# IP_ZONE. The list is routing_domains (library/common.sh), the same one the
# auth-registrar's REDIRECT_HOST_SUFFIXES is built from, so every host an app is
# published on is one its login accepts. Maison republishes every app only when the
# value differs from the stored one, so re-asserting it every run costs nothing. A
# Maison older than the routing setting (1.1.80) refuses it, which fails this check
# until the pinned image is running.
routing_setting_json | maison_cli settings set routing --owner "$OWNER" || CLI_FAILED=1

# The store: the user's list, but the deployment's own store is always on it.
STORE_URL="$(env_get APPSTORE_URL)"
maison_cli stores ensure "${STORE_URL:-https://github.com/Yundera/AppStore/archive/refs/heads/main.zip}" \
    || CLI_FAILED=1

# Feedback: on while an operator layer has written both FEEDBACK_* keys into the
# mesh .env, released otherwise. The token goes to Maison's secret store; the
# setting only references it.
FEEDBACK_URL_VAL="$(env_get FEEDBACK_URL)"
FEEDBACK_TOKEN_VAL="$(env_get FEEDBACK_TOKEN)"
if [ -n "$FEEDBACK_URL_VAL" ] && [ -n "$FEEDBACK_TOKEN_VAL" ] && json_safe "$FEEDBACK_URL_VAL"; then
    { printf '%s' "$FEEDBACK_TOKEN_VAL" | maison_cli secret set feedback_token \
        && printf '{"url":"%s","token":"${secret:feedback_token}"}' "$FEEDBACK_URL_VAL" \
            | maison_cli settings set feedback --owner "$OWNER"; } || CLI_FAILED=1
else
    maison_cli settings release feedback || CLI_FAILED=1
fi

if [ "$CLI_FAILED" -ne 0 ]; then
    log_error "Maison refused one or more managed settings (see above)"
    exit 1
fi
exit "$DEPLOY_RC"
